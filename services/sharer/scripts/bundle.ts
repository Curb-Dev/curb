// Builds browser/curb-share.mjs: the CURB-SHARE v1 calculator, the epoch file
// checks and the proof builders as one ESM file with no imports, for the web
// verify panel (`import * as share from './curb-share.mjs'`).
//
//   node scripts/bundle.ts           write the bundle
//   node scripts/bundle.ts --check   exit 1 if the committed bundle is stale

import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BUNDLE = join(ROOT, 'browser', 'curb-share.mjs');

export async function bundleText(): Promise<string> {
  const r = await build({
    entryPoints: [join(ROOT, 'src', 'calc', 'index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    write: false,
    minify: true,
    treeShaking: true,
    legalComments: 'eof',
    charset: 'utf8',
    absWorkingDir: ROOT,
    banner: {
      js: '// curb-share.mjs - the CURB-SHARE v1 calculator for the browser. Generated by services/sharer/scripts/bundle.ts from src/calc; do not edit.',
    },
    logLevel: 'silent',
  });
  if (r.errors.length) throw new Error(r.errors.map((e) => e.text).join('\n'));
  return new TextDecoder().decode(r.outputFiles[0].contents);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const text = await bundleText();
  if (process.argv.includes('--check')) {
    const have = existsSync(BUNDLE) ? readFileSync(BUNDLE, 'utf8') : '';
    if (have !== text) {
      console.error('browser/curb-share.mjs is stale: run npm run bundle');
      process.exit(1);
    }
    console.log(`browser/curb-share.mjs is current (${text.length} bytes)`);
  } else {
    mkdirSync(dirname(BUNDLE), { recursive: true });
    writeFileSync(BUNDLE, text);
    console.log(`wrote browser/curb-share.mjs (${text.length} bytes)`);
  }
}
